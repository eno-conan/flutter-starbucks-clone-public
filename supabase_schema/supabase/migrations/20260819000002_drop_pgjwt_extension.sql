-- pgjwt 拡張を削除する
--
-- 背景:
--   Supabase のパスキー（WebAuthn）は Auth v2.188.0 以降で提供される。
--   本プロジェクトの Auth は v2.176.1（2025-06-11 リリース）で止まっており、
--   /auth/v1/passkeys/* が 404 を返してパスキーが一切動作しなかった。
--
--   Supabase Cloud では Auth / PostgREST / Postgres がプラットフォームの
--   イメージとして一体で更新されるため、Auth を上げるには Postgres の
--   アップグレードが必要になる。そのアップグレードの事前条件として
--   「未サポート拡張である pgjwt の削除」が要求された。
--
-- 安全性の確認:
--   pgjwt が提供する sign() / verify() の使用箇所がリポジトリ内に存在しないこと、
--   および DB 上の関数定義にも参照がないことを確認済み。
--   古い Supabase プロジェクトのテンプレートに既定で含まれていた未使用の拡張。
--
--   pgjwt は pgcrypto に依存するが、pgcrypto は他でも使われうるため
--   CASCADE は使わない。
--
-- 結果:
--   Postgres 15.8.1.106 → 17.6.1.155、Auth 2.176.1 → 2.195.0 へ更新され、
--   パスキーのエンドポイントが 200 を返すようになった。
DROP EXTENSION IF EXISTS pgjwt;
